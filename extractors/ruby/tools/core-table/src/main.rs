//! Generates `extractors/ruby/data/core-rbs-<version>.tsv`: what the Ruby VM
//! defines before any file runs — constants, their ancestry and their methods —
//! read from RBS `core/` signatures with RBS's own parser. A development tool:
//! the extractor embeds its OUTPUT and never links this crate, so neither Ruby
//! nor RBS is needed to build or run it.
//!
//! usage: codegraph-ruby-core-table <rbs>/core <rbs version> > data/core-rbs-<version>.tsv
//!
//! One record per line, tab-separated, sorted:
//!
//! ```text
//! class    Array   Object        a class and its superclass (empty for BasicObject)
//! module   Comparable
//! const    ARGV                  a value constant
//! include  Array   Enumerable    a module mixed into instances
//! def      Array   map           an instance method (attribute readers and aliases included)
//! sdef     File    read          a singleton method
//! ```

use ruby_rbs::node::{AliasKind, AttributeKind, MethodDefinitionKind, Node, NodeList, TypeNameNode, parse};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// `core/rbs/` declares RBS's own helper namespace (`RBS::Unnamed`), which no VM defines.
const NOT_THE_VM: &[&str] = &["rbs"];

#[derive(Default)]
struct Table {
    /// Constant path → `class` / `module` / `const`.
    kinds: BTreeMap<String, &'static str>,
    /// Class → the scope it was written in and its superclass as written.
    supers: BTreeMap<String, (String, String)>,
    /// (owner, the scope it was written in, the module as written).
    includes: BTreeSet<(String, String, String)>,
    /// (`def` | `sdef`, owner, name).
    methods: BTreeSet<(&'static str, String, String)>,
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [core_dir, version] = args.as_slice() else {
        eprintln!("usage: codegraph-ruby-core-table <rbs>/core <rbs version>");
        return ExitCode::from(2);
    };
    let mut files = Vec::new();
    if let Err(error) = collect(Path::new(core_dir), true, &mut files) {
        eprintln!("cannot read {core_dir}: {error}");
        return ExitCode::FAILURE;
    }
    files.sort();

    let mut table = Table::default();
    for file in &files {
        let source = match fs::read_to_string(file) {
            Ok(source) => source,
            Err(error) => {
                eprintln!("cannot read {}: {error}", file.display());
                return ExitCode::FAILURE;
            }
        };
        let signature = match parse(&source) {
            Ok(signature) => signature,
            Err(error) => {
                eprintln!("{}: {error}", file.display());
                return ExitCode::FAILURE;
            }
        };
        declarations(&signature.declarations(), "", &mut table);
    }

    let mut lines: BTreeSet<String> = BTreeSet::new();
    for (name, kind) in &table.kinds {
        match *kind {
            "class" => {
                // RBS leaves `< Object` implicit, as Ruby does.
                let superclass = match table.supers.get(name) {
                    Some((scope, written)) => resolve(&table, scope, written),
                    None if name == "BasicObject" => String::new(),
                    None => "Object".to_owned(),
                };
                lines.insert(format!("class\t{name}\t{superclass}"));
            }
            kind => {
                lines.insert(format!("{kind}\t{name}"));
            }
        }
    }
    for (owner, scope, written) in &table.includes {
        lines.insert(format!("include\t{owner}\t{}", resolve(&table, scope, written)));
    }
    for (kind, owner, name) in &table.methods {
        lines.insert(format!("{kind}\t{owner}\t{name}"));
    }

    println!("# rbs {version} core/ — generated by extractors/ruby/tools/core-table, never edited");
    for line in &lines {
        println!("{line}");
    }
    eprintln!(
        "{} files, {} constants, {} mixins, {} methods",
        files.len(),
        table.kinds.len(),
        table.includes.len(),
        table.methods.len()
    );
    ExitCode::SUCCESS
}

fn collect(dir: &Path, top: bool, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("").to_owned();
        if path.is_dir() {
            if !(top && NOT_THE_VM.contains(&name.as_str())) {
                collect(&path, false, out)?;
            }
        } else if name.ends_with(".rbs") {
            out.push(path);
        }
    }
    Ok(())
}

fn declarations(nodes: &NodeList<'_>, scope: &str, table: &mut Table) {
    for node in nodes.iter() {
        match node {
            Node::Class(class) => {
                let name = qualify(scope, &class.name());
                record(table, &name, "class");
                if let Some(superclass) = class.super_class() {
                    table
                        .supers
                        .insert(name.clone(), (scope.to_owned(), written(&superclass.name())));
                }
                members(&class.members(), &name, table);
            }
            Node::Module(module) => {
                let name = qualify(scope, &module.name());
                record(table, &name, "module");
                members(&module.members(), &name, table);
            }
            Node::ClassAlias(alias) => record(table, &qualify(scope, &alias.new_name()), "class"),
            Node::ModuleAlias(alias) => record(table, &qualify(scope, &alias.new_name()), "module"),
            Node::Constant(constant) => record(table, &qualify(scope, &constant.name()), "const"),
            _ => {}
        }
    }
}

/// What a class or module body declares: nested constants, mixins, methods.
fn members(nodes: &NodeList<'_>, owner: &str, table: &mut Table) {
    declarations(nodes, owner, table);
    let mut method = |kind: &'static str, name: &str| {
        table.methods.insert((kind, owner.to_owned(), name.to_owned()));
    };
    for node in nodes.iter() {
        match node {
            Node::MethodDefinition(definition) => {
                let name = definition.name();
                match definition.kind() {
                    MethodDefinitionKind::Instance => method("def", name.as_str()),
                    MethodDefinitionKind::Singleton => method("sdef", name.as_str()),
                    // `def self?.x` — a module function: callable both ways.
                    MethodDefinitionKind::SingletonInstance => {
                        method("def", name.as_str());
                        method("sdef", name.as_str());
                    }
                }
            }
            Node::Alias(alias) => {
                let name = alias.new_name();
                method(
                    if matches!(alias.kind(), AliasKind::Singleton) {
                        "sdef"
                    } else {
                        "def"
                    },
                    name.as_str(),
                );
            }
            Node::AttrReader(attr) => method(attr_kind(attr.kind()), attr.name().as_str()),
            Node::AttrWriter(attr) => method(attr_kind(attr.kind()), &format!("{}=", attr.name().as_str())),
            Node::AttrAccessor(attr) => {
                let kind = attr_kind(attr.kind());
                method(kind, attr.name().as_str());
                method(kind, &format!("{}=", attr.name().as_str()));
            }
            _ => {}
        }
    }
    for node in nodes.iter() {
        if let Node::Include(include) = node {
            table
                .includes
                .insert((owner.to_owned(), owner.to_owned(), written(&include.name())));
        }
    }
}

fn attr_kind(kind: AttributeKind) -> &'static str {
    if matches!(kind, AttributeKind::Singleton) {
        "sdef"
    } else {
        "def"
    }
}

/// A type declared under two spellings stays a type; a `const` never overrides one.
fn record(table: &mut Table, name: &str, kind: &'static str) {
    match table.kinds.get(name) {
        Some(&existing) if existing == kind || kind == "const" => {}
        Some(&existing) if existing != "const" => {
            eprintln!("warning: {name} is declared as {existing} and as {kind}; keeping {existing}");
        }
        _ => {
            table.kinds.insert(name.to_owned(), kind);
        }
    }
}

fn segments(name: &TypeNameNode<'_>) -> Vec<String> {
    let mut segments: Vec<String> = Vec::new();
    for segment in name.namespace().path().iter() {
        if let Node::Symbol(symbol) = segment {
            segments.push(symbol.as_str().to_owned());
        }
    }
    segments.push(name.name().as_str().to_owned());
    segments
}

/// A name as written, `::`-prefixed when absolute — resolved once every declaration is known.
fn written(name: &TypeNameNode<'_>) -> String {
    let path = segments(name).join("::");
    if name.namespace().absolute() {
        format!("::{path}")
    } else {
        path
    }
}

fn qualify(scope: &str, name: &TypeNameNode<'_>) -> String {
    let path = segments(name).join("::");
    if name.namespace().absolute() || scope.is_empty() {
        path
    } else {
        format!("{scope}::{path}")
    }
}

/// RBS resolves a name as Ruby does lexically: each enclosing scope, then the top level.
fn resolve(table: &Table, scope: &str, written: &str) -> String {
    if let Some(absolute) = written.strip_prefix("::") {
        return absolute.to_owned();
    }
    let mut scope = scope;
    loop {
        if scope.is_empty() {
            return written.to_owned();
        }
        let candidate = format!("{scope}::{written}");
        if table.kinds.contains_key(&candidate) {
            return candidate;
        }
        scope = scope.rsplit_once("::").map(|(outer, _)| outer).unwrap_or("");
    }
}
