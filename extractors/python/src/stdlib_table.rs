//! The embedded table of the Python standard library — the ct.sym of this
//! extractor: every module of typeshed's `stdlib/` (`VERSIONS`, removed ones
//! included, so keys do not move with the interpreter) and the names each
//! binds at its top level, `builtins` among them. Generated at a pinned
//! typeshed commit by `tools/stdlib-table` and committed, so a model says which
//! standard it resolved against and no Python is needed to build or run it.

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

const TABLE: &str = include_str!("../data/typeshed-stdlib-2e4d4dcf657f82305709bbe3e86bca4d27d4dd46.tsv");
/// Python 2.7's standard library, by its Library Reference's module index.
const PY2_MODULES: &str = include_str!("../data/stdlib-py2.txt");
/// Python 2.7's builtins Python 3 does not have.
const PY2_BUILTINS: &str = include_str!("../data/builtins-py2.txt");

/// What a module of the table binds a name to.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    Class,
    Function,
    Value,
    /// Another module of the table, by its dotted name.
    Module(&'static str),
}

/// A class of the table where its module declares it: `(module, name)`.
pub type ClassRef = (&'static str, &'static str);

/// What a class's body binds a name to.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Member {
    Attribute,
    Class,
    Method,
    /// `@property` and its accessors: read and written as an attribute.
    Property,
}

pub struct StdlibTable {
    commit: &'static str,
    modules: HashSet<&'static str>,
    names: HashMap<(&'static str, &'static str), Kind>,
    /// Every class name → where it is declared: itself, or the module a re-export names.
    declared: HashMap<(&'static str, &'static str), ClassRef>,
    bases: HashMap<ClassRef, Vec<(u32, ClassRef)>>,
    members: HashMap<(ClassRef, &'static str), Member>,
    /// Module → its names in order, for a star import.
    module_names: HashMap<&'static str, Vec<&'static str>>,
    /// `__all__`, for the modules whose stub writes one.
    all: HashMap<&'static str, Vec<&'static str>>,
}

impl StdlibTable {
    /// The typeshed commit the table was distilled from.
    pub fn commit(&self) -> &'static str {
        self.commit
    }

    pub fn is_module(&self, dotted: &str) -> bool {
        self.modules.contains(dotted)
    }

    /// What `module` binds `name` to at its top level, if its stub says.
    pub fn name(&self, module: &str, name: &str) -> Option<Kind> {
        self.names.get(&(module, name)).copied()
    }

    /// A name of `builtins`: what the interpreter binds before any file runs.
    pub fn builtin(&self, name: &str) -> Option<Kind> {
        self.name("builtins", name)
    }

    /// The class `module.name` is, where its own module declares it.
    pub fn class(&self, module: &str, name: &str) -> Option<ClassRef> {
        self.declared.get(&(module, name)).copied()
    }

    /// A class's bases, in the order its stub writes them; those no stub resolves are left out.
    pub fn bases(&self, class: ClassRef) -> Vec<ClassRef> {
        self.bases
            .get(&class)
            .map(|bases| bases.iter().map(|(_, base)| *base).collect())
            .unwrap_or_default()
    }

    /// What the class itself — not an ancestor — binds `name` to.
    pub fn member(&self, class: ClassRef, name: &str) -> Option<Member> {
        self.members.get(&(class, name)).copied()
    }

    /// What `from module import *` binds: `__all__`, else every public name.
    pub fn exports(&self, module: &str) -> Vec<&'static str> {
        if let Some(all) = self.all.get(module) {
            return all.clone();
        }
        self.module_names
            .get(module)
            .map(|names| names.iter().copied().filter(|name| !name.starts_with('_')).collect())
            .unwrap_or_default()
    }
}

/// `a.b.C` → (`a.b`, `C`).
fn class_ref(dotted: &'static str) -> ClassRef {
    dotted.rsplit_once('.').expect("a class is module.name")
}

pub fn table() -> &'static StdlibTable {
    static TABLE_ONCE: OnceLock<StdlibTable> = OnceLock::new();
    TABLE_ONCE.get_or_init(|| parse(TABLE))
}

fn parse(text: &'static str) -> StdlibTable {
    let mut lines = text.lines();
    // `# typeshed <commit> stdlib/ — generated by …`
    let commit = lines
        .next()
        .and_then(|header| header.strip_prefix("# typeshed "))
        .and_then(|rest| rest.split(' ').next())
        .expect("the stdlib table starts with its typeshed commit");
    let mut table = StdlibTable {
        commit,
        modules: HashSet::new(),
        names: HashMap::new(),
        declared: HashMap::new(),
        bases: HashMap::new(),
        members: HashMap::new(),
        module_names: HashMap::new(),
        all: HashMap::new(),
    };
    for line in lines {
        let fields: Vec<&'static str> = line.split('\t').collect();
        match fields.as_slice() {
            // The version range is the generator's record of why a removed module is listed.
            ["module", module, _range] => {
                table.modules.insert(module);
            }
            ["name", module, name, "module", target] => {
                table.names.insert((module, name), Kind::Module(target));
                table.module_names.entry(module).or_default().push(name);
            }
            ["name", module, name, "class", target] => {
                table.names.insert((module, name), Kind::Class);
                table.declared.insert((module, name), class_ref(target));
                table.module_names.entry(module).or_default().push(name);
            }
            ["name", module, name, kind] => {
                let kind = match *kind {
                    "class" => Kind::Class,
                    "function" => Kind::Function,
                    "value" => Kind::Value,
                    other => panic!("stdlib table: unknown kind {other:?}"),
                };
                if kind == Kind::Class {
                    table.declared.insert((module, name), (module, name));
                }
                table.names.insert((module, name), kind);
                table.module_names.entry(module).or_default().push(name);
            }
            ["base", class, index, base] => {
                let index = index.parse().expect("a base's index is a number");
                let bases = table.bases.entry(class_ref(class)).or_default();
                bases.push((index, class_ref(base)));
                bases.sort();
            }
            ["member", class, name, kind] => {
                let member = match *kind {
                    "attribute" => Member::Attribute,
                    "class" => Member::Class,
                    "method" => Member::Method,
                    "property" => Member::Property,
                    other => panic!("stdlib table: unknown member kind {other:?}"),
                };
                table.members.insert((class_ref(class), name), member);
            }
            ["all", module, names] => {
                table
                    .all
                    .insert(module, names.split(' ').filter(|name| !name.is_empty()).collect());
            }
            _ => panic!("stdlib table: unknown record {line:?}"),
        }
    }
    // Python 2's names after Python 3's, which answer first.
    for module in PY2_MODULES
        .lines()
        .filter(|line| !line.starts_with('#') && !line.is_empty())
    {
        table.modules.insert(module);
    }
    for line in PY2_BUILTINS
        .lines()
        .filter(|line| !line.starts_with('#') && !line.is_empty())
    {
        let fields: Vec<&'static str> = line.split('\t').collect();
        let (kind, name, base) = match fields.as_slice() {
            ["class", name, base] => (Kind::Class, *name, Some(*base)),
            ["function", name] => (Kind::Function, *name, None),
            _ => panic!("python 2 builtins: unknown record {line:?}"),
        };
        if table.names.contains_key(&("builtins", name)) {
            continue;
        }
        table.names.insert(("builtins", name), kind);
        if let Some(base) = base {
            table.declared.insert(("builtins", name), ("builtins", name));
            table.bases.insert(("builtins", name), vec![(0, ("builtins", base))]);
        }
    }
    table
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_the_typeshed_commit_it_was_distilled_from() {
        assert_eq!(table().commit(), "2e4d4dcf657f82305709bbe3e86bca4d27d4dd46");
    }

    #[test]
    fn knows_every_module_removed_ones_included_and_nothing_typeshed_alone_ships() {
        let stdlib = table();
        for module in [
            "os",
            "os.path",
            "collections.abc",
            "xml.etree.ElementTree",
            "asynchat",
            "distutils.core",
            "__future__",
        ] {
            assert!(stdlib.is_module(module), "{module}");
        }
        // The stubs' own helpers and a PyPI distribution type checkers bundle.
        for module in ["_typeshed", "_typeshed.wsgi", "typing_extensions", "django", "os.nope"] {
            assert!(!stdlib.is_module(module), "{module}");
        }
        assert!(stdlib.modules.len() > 700);
    }

    #[test]
    fn knows_what_a_module_binds_and_as_what() {
        let stdlib = table();
        assert_eq!(stdlib.name("enum", "Enum"), Some(Kind::Class));
        assert_eq!(stdlib.name("abc", "ABC"), Some(Kind::Class));
        assert_eq!(stdlib.name("collections.abc", "Mapping"), Some(Kind::Class));
        assert_eq!(stdlib.name("os", "getcwd"), Some(Kind::Function));
        assert_eq!(stdlib.name("os", "sep"), Some(Kind::Value));
        assert_eq!(stdlib.name("os", "path"), Some(Kind::Module("os.path")));
        // `collections` does not bind `abc`: `from collections import abc` is the submodule.
        assert_eq!(stdlib.name("collections", "abc"), None);
        assert_eq!(stdlib.builtin("ValueError"), Some(Kind::Class));
        assert_eq!(stdlib.builtin("object"), Some(Kind::Class));
        assert_eq!(stdlib.builtin("len"), Some(Kind::Function));
        // A stub-only class is no builtin, and neither is a private name.
        assert_eq!(stdlib.builtin("function"), None);
        assert_eq!(stdlib.builtin("_T"), None);
    }

    #[test]
    fn reads_python_2s_standard_library_and_builtins_where_python_3_has_none() {
        let stdlib = table();
        // The 2.7 Library Reference's index: what Python 3 dropped is still the standard library.
        for module in [
            "ConfigParser",
            "urllib2",
            "cPickle",
            "StringIO",
            "Tkinter",
            "__builtin__",
            "md5",
        ] {
            assert!(stdlib.is_module(module), "{module}");
        }
        assert!(!stdlib.is_module("simplejson"));
        assert_eq!(stdlib.builtin("StandardError"), Some(Kind::Class));
        assert_eq!(stdlib.bases(("builtins", "StandardError")), [("builtins", "Exception")]);
        assert_eq!(stdlib.builtin("unicode"), Some(Kind::Class));
        assert_eq!(stdlib.bases(("builtins", "unicode")), [("builtins", "basestring")]);
        assert_eq!(stdlib.class("builtins", "long"), Some(("builtins", "long")));
        assert_eq!(stdlib.builtin("raw_input"), Some(Kind::Function));
        // A keyword in Python 3 is the language, in either.
        assert_eq!(stdlib.builtin("True"), None);
        // Python 3 answers first: its `str` is typeshed's, no Python 2 name.
        assert_eq!(stdlib.bases(("builtins", "str")), [("typing", "Sequence")]);
    }

    #[test]
    fn knows_where_a_class_is_declared_what_it_inherits_and_what_it_holds() {
        let stdlib = table();
        // A re-export names the class where its module declares it.
        assert_eq!(
            stdlib.class("unittest", "TestCase"),
            Some(("unittest.case", "TestCase"))
        );
        assert_eq!(stdlib.class("enum", "Enum"), Some(("enum", "Enum")));
        assert_eq!(stdlib.class("collections.abc", "Mapping"), Some(("typing", "Mapping")));
        assert_eq!(stdlib.class("os", "getcwd"), None);
        assert_eq!(stdlib.bases(("collections", "OrderedDict")), [("builtins", "dict")]);
        assert_eq!(stdlib.bases(("builtins", "ValueError")), [("builtins", "Exception")]);
        assert!(stdlib.bases(("builtins", "object")).is_empty());
        assert_eq!(
            stdlib.member(("unittest.case", "TestCase"), "assertEqual"),
            Some(Member::Method)
        );
        assert_eq!(stdlib.member(("builtins", "int"), "real"), Some(Member::Property));
        assert_eq!(stdlib.member(("builtins", "object"), "__init__"), Some(Member::Method));
        assert_eq!(
            stdlib.member(("builtins", "BaseException"), "args"),
            Some(Member::Attribute)
        );
        assert_eq!(stdlib.member(("unittest.case", "TestCase"), "assertNothing"), None);
        // A star import binds `__all__` where the stub writes one, else the public names.
        assert!(stdlib.exports("collections.abc").contains(&"Mapping"));
        let string = stdlib.exports("string");
        assert!(string.contains(&"Template") && !string.iter().any(|name| name.starts_with('_')));
    }
}
